//! BountyVault — on-chain escrow for bug bounties on Tari Ootle.
//!
//! The problem: sponsors ghost hunters, and hunters fear non-payment. A sponsor locks the
//! bounty in TARI when the bounty is created. A hunter submits only a hash of their report —
//! the report itself never goes on chain, so a public bounty board does not leak what was
//! found, or where. The sponsor approves (the whole vault pays the hunter) or rejects (the
//! bounty reopens). A hunter who disagrees can dispute, and a referee named at creation —
//! who can never be changed — settles it. A bounty nobody claims refunds in full once its
//! deadline epoch passes.
//!
//! Every payout moves the whole vault: no partial amounts, no dust left behind. The sponsor
//! can never pay themselves through `approve` — it only ever pays the recorded hunter.

use tari_template_lib::prelude::*;

#[template]
mod bounty_vault {
    use super::*;

    pub struct BountyVault {
        /// The sponsor: the key that created the bounty. Only this key can approve,
        /// reject, or cancel. Recorded as a public key so the check is the engine's
        /// transaction signer, not an address anyone could pass in.
        sponsor: RistrettoPublicKeyBytes,
        /// The sponsor's account, where refunds go. Supplied at creation; the sponsor
        /// is the only party hurt by supplying a wrong one.
        sponsor_account: ComponentAddress,
        /// The referee: fixed at creation, never changeable. Only this key can resolve
        /// a dispute.
        referee: RistrettoPublicKeyBytes,
        /// SHA-256 of the scope text. The scope itself stays off-chain.
        scope_hash: Hash32,
        /// The last epoch a report may be submitted in. Submissions close once the
        /// chain reaches this epoch.
        deadline_epoch: u64,
        /// The bounty, as locked at creation. Never changes; payouts always move the
        /// whole vault, so this is also the exact amount any payout sends.
        amount: Amount,
        state: BountyState,
        submission: Option<Submission>,
        vault: Vault,
    }

    /// The bounty lifecycle. Only one transition is allowed out of each state; every
    /// transition is enforced inside the template, never just by the UI.
    /// (Encode/Decode impls are generated by the #[template] macro.)
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum BountyState {
        Open,
        Submitted,
        Disputed,
        Paid,
        Refunded,
    }

    /// A hunter's claim on the bounty: who they are, where they get paid, the hash of
    /// their report, and the epoch they submitted in. The report itself stays off-chain.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub struct Submission {
        hunter: RistrettoPublicKeyBytes,
        hunter_account: ComponentAddress,
        report_hash: Hash32,
        epoch: u64,
    }

    impl BountyVault {
        /// Creates a bounty and locks the funds in the component vault.
        ///
        /// The caller becomes the sponsor. `bucket` must be TARI and non-empty; the
        /// deadline must be in the future; the referee must differ from the sponsor.
        pub fn create(
            bucket: Bucket,
            scope_hash: Hash32,
            deadline_epoch: u64,
            referee: RistrettoPublicKeyBytes,
            sponsor_account: ComponentAddress,
        ) -> Component<Self> {
            assert!(bucket.resource_address() == TARI_TOKEN, "bounty funds must be in TARI");
            let amount = bucket.amount();
            assert!(amount.is_positive(), "amount must be more than zero");
            assert!(
                deadline_epoch > Consensus::current_epoch(),
                "deadline must be in the future"
            );
            let sponsor = CallerContext::transaction_signer_public_key();
            assert!(referee != sponsor, "referee must differ from the sponsor");

            let vault = Vault::new_empty(TARI_TOKEN);
            vault.deposit(bucket);

            // Every method is callable by anyone; the sponsor / hunter / referee checks
            // live inside the methods, against the engine's transaction signer.
            let access_rules = ComponentAccessRules::new()
                .method("submit", rule![allow_all])
                .method("approve", rule![allow_all])
                .method("reject", rule![allow_all])
                .method("dispute", rule![allow_all])
                .method("resolve", rule![allow_all])
                .method("cancel", rule![allow_all])
                .method("timeout", rule![allow_all])
                .method("get_state", rule![allow_all])
                .method("get_details", rule![allow_all]);

            emit_event("Created", metadata![
                "amount" => amount,
                "deadline_epoch" => deadline_epoch,
                "state" => String::from("Open"),
            ]);

            Component::new(Self {
                sponsor,
                sponsor_account,
                referee,
                scope_hash,
                deadline_epoch,
                amount,
                state: BountyState::Open,
                submission: None,
                vault,
            })
            .with_access_rules(access_rules)
            .create()
        }

        /// Submits a report hash for the bounty. Only while Open and before the
        /// deadline. The caller is recorded as the hunter, together with the account
        /// they want to be paid into.
        pub fn submit(&mut self, report_hash: Hash32, hunter_account: ComponentAddress) {
            assert!(self.state == BountyState::Open, "bounty is not Open");
            assert!(
                Consensus::current_epoch() < self.deadline_epoch,
                "deadline has passed"
            );
            assert!(self.submission.is_none(), "a submission is already waiting");
            let hunter = CallerContext::transaction_signer_public_key();
            self.submission = Some(Submission {
                hunter,
                hunter_account,
                report_hash,
                epoch: Consensus::current_epoch(),
            });
            self.state = BountyState::Submitted;
            emit_event("Submitted", metadata![
                "amount" => self.amount,
                "state" => String::from("Submitted"),
            ]);
        }

        /// Approves the waiting submission. Sponsor only. Pays the entire vault to the
        /// recorded hunter — never to the sponsor, never a partial amount.
        pub fn approve(&mut self) {
            assert!(self.state == BountyState::Submitted, "bounty is not Submitted");
            assert!(
                CallerContext::transaction_signer_public_key() == self.sponsor,
                "only the sponsor can approve"
            );
            let submission = self.submission.expect("Submitted without a submission");
            let balance = self.vault.balance();
            let bucket = self.vault.withdraw(balance);
            ComponentManager::get(submission.hunter_account).invoke("deposit", args![bucket]);
            self.state = BountyState::Paid;
            emit_event("Approved", metadata![
                "amount" => balance,
                "state" => String::from("Paid"),
            ]);
        }

        /// Rejects the waiting submission. Sponsor only. Clears the submission and
        /// reopens the bounty; the funds stay locked for the next hunter.
        pub fn reject(&mut self) {
            assert!(self.state == BountyState::Submitted, "bounty is not Submitted");
            assert!(
                CallerContext::transaction_signer_public_key() == self.sponsor,
                "only the sponsor can reject"
            );
            self.submission = None;
            self.state = BountyState::Open;
            emit_event("Rejected", metadata![
                "amount" => self.amount,
                "state" => String::from("Open"),
            ]);
        }

        /// Disputes the waiting submission. Only the hunter who submitted it. The funds
        /// stay locked until the referee resolves.
        pub fn dispute(&mut self) {
            assert!(self.state == BountyState::Submitted, "bounty is not Submitted");
            let submission = self.submission.expect("Submitted without a submission");
            assert!(
                CallerContext::transaction_signer_public_key() == submission.hunter,
                "only the hunter who submitted can dispute"
            );
            self.state = BountyState::Disputed;
            emit_event("Disputed", metadata![
                "amount" => self.amount,
                "state" => String::from("Disputed"),
            ]);
        }

        /// Resolves a dispute. Referee only. `pay_hunter = true` pays the whole vault
        /// to the hunter; `false` refunds the whole vault to the sponsor.
        pub fn resolve(&mut self, pay_hunter: bool) {
            assert!(self.state == BountyState::Disputed, "bounty is not Disputed");
            assert!(
                CallerContext::transaction_signer_public_key() == self.referee,
                "only the referee can resolve"
            );
            let submission = self.submission.expect("Disputed without a submission");
            let balance = self.vault.balance();
            let bucket = self.vault.withdraw(balance);
            let payee = if pay_hunter { submission.hunter_account } else { self.sponsor_account };
            ComponentManager::get(payee).invoke("deposit", args![bucket]);
            self.state = if pay_hunter { BountyState::Paid } else { BountyState::Refunded };
            emit_event("Resolved", metadata![
                "amount" => balance,
                "state" => String::from(Self::state_name(self.state)),
            ]);
        }

        /// Cancels the bounty. Sponsor only, and only while Open with no submission
        /// waiting. Refunds the whole vault to the sponsor.
        pub fn cancel(&mut self) {
            assert!(self.state == BountyState::Open, "bounty is not Open");
            assert!(
                CallerContext::transaction_signer_public_key() == self.sponsor,
                "only the sponsor can cancel"
            );
            assert!(self.submission.is_none(), "cannot cancel while a submission is waiting");
            let balance = self.vault.balance();
            let bucket = self.vault.withdraw(balance);
            ComponentManager::get(self.sponsor_account).invoke("deposit", args![bucket]);
            self.state = BountyState::Refunded;
            emit_event("Cancelled", metadata![
                "amount" => balance,
                "state" => String::from("Refunded"),
            ]);
        }

        /// Refunds an unclaimed bounty after its deadline. Anyone may call it, but only
        /// while Open and only once the chain has reached the deadline epoch.
        pub fn timeout(&mut self) {
            assert!(self.state == BountyState::Open, "bounty is not Open");
            assert!(
                Consensus::current_epoch() >= self.deadline_epoch,
                "deadline has not been reached"
            );
            let balance = self.vault.balance();
            let bucket = self.vault.withdraw(balance);
            ComponentManager::get(self.sponsor_account).invoke("deposit", args![bucket]);
            self.state = BountyState::Refunded;
            emit_event("Refunded", metadata![
                "amount" => balance,
                "state" => String::from("Refunded"),
            ]);
        }

        /// Returns the current state as a string: Open, Submitted, Disputed, Paid, or
        /// Refunded.
        pub fn get_state(&self) -> String {
            String::from(Self::state_name(self.state))
        }

        /// Returns (state, amount, vault balance, scope hash, deadline epoch, sponsor,
        /// referee, submission). The submission is (hunter, hunter account, report hash,
        /// epoch) while one is waiting or was paid, and None otherwise.
        pub fn get_details(
            &self,
        ) -> (
            String,
            Amount,
            Amount,
            Hash32,
            u64,
            RistrettoPublicKeyBytes,
            RistrettoPublicKeyBytes,
            Option<(RistrettoPublicKeyBytes, ComponentAddress, Hash32, u64)>,
        ) {
            (
                String::from(Self::state_name(self.state)),
                self.amount,
                self.vault.balance(),
                self.scope_hash,
                self.deadline_epoch,
                self.sponsor,
                self.referee,
                self.submission.map(|s| (s.hunter, s.hunter_account, s.report_hash, s.epoch)),
            )
        }

        /// Private helper: the state's name. Kept private so the template dispatcher
        /// ignores it (only public methods become on-chain calls).
        fn state_name(state: BountyState) -> &'static str {
            match state {
                BountyState::Open => "Open",
                BountyState::Submitted => "Submitted",
                BountyState::Disputed => "Disputed",
                BountyState::Paid => "Paid",
                BountyState::Refunded => "Refunded",
            }
        }
    }
}
